/**
 * Actual application command and Spring transaction. JDBC adapters model the local record/stock boundary; real PG,
 * stock allocator, MDM HTTP and security are separate integration checks.
 */
class WmsMobileMoveTransactionTest {
	private JdbcTemplate db;
	private WmsMaterialMoveSiteServiceImpl service;
	private RemoteWarehouseLocationService locations;
	private RemoteWarehouseService warehouses;
	private WmsLiveStockService stocks;
	private final List<String> lookedUp = new ArrayList<>();
	private boolean failSave, failStock, falseStock;
	private List<WmsStockMoveSlice> moveSlices;

	@BeforeEach
	void setup() throws Exception {
		var ds = new DriverManagerDataSource("jdbc:h2:mem:mobile-move-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1",
				"sa", "");
		ds.setDriverClassName("org.h2.Driver");
		db = new JdbcTemplate(ds);
		db.execute("create table movement(id bigint generated by default as identity primary key, quantity double "
				+ "precision, factory varchar(30), old_site varchar(30), new_site "
				+ "varchar(30), bill_no varchar(80), source_stock_id bigint, source_detail_id bigint)");
		db.execute("create table stock(id bigint primary key, quantity double precision)");
		db.execute("create table move_request(tenant_id bigint, factory_code varchar(40), request_id varchar(64), "
				+ "fingerprint varchar(64), bill_no varchar(80), primary key(tenant_id,factory_code,request_id), "
				+ "unique(tenant_id,factory_code,bill_no))");
		db.update("insert into stock values(1,10)");
		locations = mock(RemoteWarehouseLocationService.class);
		warehouses = mock(RemoteWarehouseService.class);
		stocks = mock(WmsLiveStockService.class);
		when(locations.getByCode(anyString())).thenAnswer(call -> {
			String code = call.getArgument(0);
			lookedUp.add(code);
			// A real location may share the warehouse code: this exposes the old wrong lookup without an unrelated null
			// failure.
			return R.ok(location(code));
		});
		var warehouse = new MdmWarehouseEntity();
		warehouse.setWarehouseCode("W1");
		warehouse.setWarehouseName("Warehouse");
		warehouse.setTenantId(1L);
		warehouse.setFactoryCode("F1");
		warehouse.setStatus(true);
		when(warehouses.getByCode("W1")).thenReturn(R.ok(warehouse));
		moveSlices = List.of(slice(1L, 81L, 2d));
		when(stocks.billStockMoveWithEvidence(any())).thenAnswer(call -> {
			db.update("update stock set quantity=8 where id=1");
			if (failStock) {
				throw new IllegalStateException("stock write failed");
			}
			return falseStock ? List.of() : moveSlices;
		});
		var mapper = mock(WmsMaterialMoveSiteMapper.class);
		when(mapper.reserveMobileRequest(anyLong(), anyString(), anyString(), anyString(), anyString()))
				.thenAnswer(call -> {
					try {
						return db.update("insert into move_request values(?,?,?,?,?)", call.getArgument(0),
								call.getArgument(1), call.getArgument(2), call.getArgument(3), call.getArgument(4));
					} catch (DuplicateKeyException duplicate) {
						return 0;
					}
				});
		when(mapper.findMobileRequestFingerprint(anyLong(), anyString(), anyString()))
				.thenAnswer(call -> {
					var found = db.queryForList("select fingerprint from move_request where tenant_id=? "
							+ "and factory_code=? and request_id=?", String.class, call.getArgument(0),
							call.getArgument(1), call.getArgument(2));
					return found.isEmpty() ? null : found.get(0);
				});
		when(mapper.insert(any(WmsMaterialMoveSiteEntity.class))).thenAnswer(call -> {
			if (failSave) {
				return 0;
			}
			WmsMaterialMoveSiteEntity row = call.getArgument(0);
			return db.update("insert into movement(quantity,factory,old_site,new_site,bill_no,source_stock_id,source_detail_id) "
					+ "values(?,?,?,?,?,?,?)", row.getMatNum(), row.getFactoryCode(),
					row.getOldSiteCode(), row.getNewSiteCode(), row.getBillNo(),
					row.getSourceStockId(), row.getSourceInBillDetailId());
		});
		var guard = mock(WmsWarehouseBusinessGuard.class);
		when(guard.check("W1", "move_site", false)).thenReturn(true);
		var deps = Map.of(WmsLiveStockService.class, stocks, RemoteWarehouseLocationService.class, locations,
				RemoteWarehouseService.class, warehouses, WmsWarehouseBusinessGuard.class, guard);
		var constructor = WmsMaterialMoveSiteServiceImpl.class.getConstructors()[0];
		var target = (WmsMaterialMoveSiteServiceImpl) constructor
				.newInstance(Arrays.stream(constructor.getParameterTypes()).map(deps::get).toArray());
		ReflectionTestUtils.setField(target, "baseMapper", mapper);
		var proxy = new ProxyFactory(target);
		proxy.setProxyTargetClass(true);
		proxy.addAdvice(new TransactionInterceptor(new DataSourceTransactionManager(ds),
				new AnnotationTransactionAttributeSource()));
		service = (WmsMaterialMoveSiteServiceImpl) proxy.getProxy();
		TenantContextHolder.setTenantId(1L);
		FactoryContextHolder.setFactoryCode("F1");
	}

	@AfterEach
	void clear() {
		TenantContextHolder.clear();
		FactoryContextHolder.clear();
	}

	private MdmWarehouseLocationEntity location(String code) {
		var site = new MdmWarehouseLocationEntity();
		site.setLocationCode(code);
		site.setLocationName("Name " + code);
		site.setWarehouseCode("W1");
		site.setTenantId(1L);
		site.setFactoryCode("F1");
		site.setStatus(true);
		site.setLocationLevel(3);
		return site;
	}

	private WmsStockMoveSlice slice(Long stockId, Long sourceDetailId, double quantity) {
		var source = new WmsLiveStockEntity().setWarehouseCode("W1").setSiteCode("S1")
				.setMatCode("M1").setMatBatch("B1").setSourceInBillDetailId(sourceDetailId)
				.setStockOwnerType("OWNED").setFactoryCode("F1");
		source.setId(stockId);
		source.setTenantId(1L);
		return new WmsStockMoveSlice(source, stockId + 100L, quantity);
	}

	private WmsMaterialMoveSiteAppDTO command() {
		var command = new WmsMaterialMoveSiteAppDTO();
		command.setWarehouseCode("W1");
		command.setBillNo("MOVE-1");
		command.setRequestId("request-move-1");
		command.setWarehouseName("untrusted name");
		command.setOldSiteCode("S1");
		command.setNewSiteCode("S2");
		command.setMatCode("M1");
		command.setMatBatch("B1");
		command.setSupplierCode("SUP");
		command.setMatUnit("KG");
		command.setOperateNum(2d);
		command.setFactoryCode("F2");
		return command;
	}

	private int records() {
		return db.queryForObject("select count(*) from movement", Integer.class);
	}

	private double quantity() {
		return db.queryForObject("select quantity from stock", Double.class);
	}

	@Test
	void actualSourceAndTargetLocationsAreValidatedAndOriginalQuantityIsRecorded() {
		assertTrue(service.appMaterialMoveSiteSave(command()));

		assertEquals(List.of("S1", "S2"), lookedUp);
		assertEquals(2d, db.queryForObject("select quantity from movement", Double.class));
		assertEquals("F1", db.queryForObject("select factory from movement", String.class));
	}

	@Test
	void originalMobileBillNumberSurvivesJsonBindingAndRecordSave() throws Exception {
		var json = new ObjectMapper().configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false);
		WmsMaterialMoveSiteAppDTO request = json.readerForUpdating(command()).readValue("{\"billNo\":\"MOVE-1\"}");

		assertTrue(service.appMaterialMoveSiteSave(request));

		assertEquals("MOVE-1", db.queryForObject("select bill_no from movement", String.class));
	}

	@Test
	void identicalMobileRetryReturnsCommittedReceiptWithoutMovingAgain() {
		assertTrue(service.appMaterialMoveSiteSave(command()));
		assertTrue(service.appMaterialMoveSiteSave(command()));

		assertEquals(1, records());
		assertEquals(8d, quantity());
		assertEquals(1, db.queryForObject("select count(*) from move_request", Integer.class));
		verify(stocks, times(1)).billStockMoveWithEvidence(any());
	}

	@Test
	void conflictingRetryAndReusedBillNumberCannotMoveOtherStock() {
		assertTrue(service.appMaterialMoveSiteSave(command()));
		var changed = command();
		changed.setOperateNum(1d);
		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(changed));
		var reusedBillNo = command();
		reusedBillNo.setRequestId("request-move-2");
		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(reusedBillNo));

		assertEquals(1, records());
		assertEquals(8d, quantity());
		verify(stocks, times(1)).billStockMoveWithEvidence(any());
	}

	@Test
	void failedMobileMoveLeavesNoReceiptAndSameRequestCanBeRetried() {
		failSave = true;
		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command()));
		assertEquals(0, db.queryForObject("select count(*) from move_request", Integer.class));
		failSave = false;

		assertTrue(service.appMaterialMoveSiteSave(command()));
		assertEquals(1, records());
		assertEquals(8d, quantity());
	}

	@Test
	void missingMobileRequestIdFailsBeforeAnyWrite() {
		var missing = command();
		missing.setRequestId(null);
		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(missing));
		assertEquals(0, db.queryForObject("select count(*) from move_request", Integer.class));
		verify(stocks, never()).billStockMoveWithEvidence(any());
	}

	@Test
	void exactSerialStockIdAndBarcodeSurviveMobileJsonBinding() throws Exception {
		var json = new ObjectMapper().configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false);
		WmsMaterialMoveSiteAppDTO request = json.readerForUpdating(command()).readValue(
				"{\"sourceStockId\":\"9007199254740993\",\"matBarcode\":\"SERIAL-1\"}");

		assertTrue(service.appMaterialMoveSiteSave(request));

		var captured = org.mockito.ArgumentCaptor.forClass(WmsLiveStockMoveDTO.class);
		verify(stocks).billStockMoveWithEvidence(captured.capture());
		assertEquals(9007199254740993L, captured.getValue().getSourceStockId());
		assertEquals("SERIAL-1", captured.getValue().getMatBarcode());
	}

	@Test
	void mobileMoveWritesOneRecordPerActualSourceStock() {
		moveSlices = List.of(slice(1L, 81L, 1d), slice(2L, 82L, 1d));

		assertTrue(service.appMaterialMoveSiteSave(command()));

		assertEquals(2, records());
		assertEquals(List.of(81L, 82L), db.queryForList(
				"select source_detail_id from movement order by source_stock_id", Long.class));
		assertEquals(List.of(1L, 2L), db.queryForList(
				"select source_stock_id from movement order by source_stock_id", Long.class));
	}

	@Test
	void incompleteSourceSlicesRollBackStockAndHistory() {
		moveSlices = List.of(slice(1L, 81L, 1d), slice(2L, 82L, 0.5d));

		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command()));

		assertEquals(0, records());
		assertEquals(10d, quantity());
	}

	@Test
	void stockFailureRollsBackBothMovementAndStockMutation() {
		failStock = true;

		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command()));

		assertEquals(0, records());
		assertEquals(10d, quantity());
	}

	@Test
	void falseStockReceiptMustRollBackInsteadOfReturningSuccess() {
		falseStock = true;

		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command()));

		assertEquals(0, records());
		assertEquals(10d, quantity());
	}

	@Test
	void failedRecordSaveCannotContinueMovingStock() {
		failSave = true;

		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command()));

		assertEquals(0, records());
		assertEquals(10d, quantity());
	}

	@Test
	void nonfiniteZeroAndNegativeQuantitiesAreRejectedBeforeWrites() {
		for (double value : new double[] { Double.NaN, Double.POSITIVE_INFINITY, Double.NEGATIVE_INFINITY, 0d, -1d }) {
			var command = command();
			command.setOperateNum(value);
			assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command));
			assertEquals(0, records());
			assertEquals(10d, quantity());
		}
	}

	@Test
	void missingActualOrganizationCannotFallBackToClientFactory() {
		FactoryContextHolder.clear();
		TenantContextHolder.clear();

		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command()));

		assertEquals(0, records());
		assertEquals(10d, quantity());
	}

	@Test
	void disabledForeignOrNonleafTargetIsRejectedBeforeWrites() {
		for (int change = 0; change < 5; change++) {
			var target = location("S2");
			if (change == 0) {
				target.setStatus(false);
			}
			if (change == 1) {
				target.setFactoryCode("F2");
			}
			if (change == 2) {
				target.setTenantId(2L);
			}
			if (change == 3) {
				target.setWarehouseCode("W2");
			}
			if (change == 4) {
				target.setLocationLevel(2);
			}
			when(locations.getByCode("S2")).thenReturn(R.ok(target));
			assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command()));
			assertEquals(0, records());
			assertEquals(10d, quantity());
		}
	}

	@Test
	void failedWarehouseOrLocationReadIsNotAcceptedBecauseItCarriesData() {
		var location = R.ok(location("S2"));
		location.setCode(1);
		when(locations.getByCode("S2")).thenReturn(location);

		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command()));

		assertEquals(0, records());
	}

	@Test
	void disabledWarehouseIsRejectedBeforeMoving() {
		var warehouse = new MdmWarehouseEntity();
		warehouse.setWarehouseCode("W1");
		warehouse.setTenantId(1L);
		warehouse.setFactoryCode("F1");
		warehouse.setStatus(false);
		when(warehouses.getByCode("W1")).thenReturn(R.ok(warehouse));

		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command()));

		assertEquals(0, records());
		assertEquals(10d, quantity());
	}

	@Test
	void identicalLocationAndContainerIsNotARealMove() {
		var command = command();
		command.setNewSiteCode("S1");

		assertThrows(RuntimeException.class, () -> service.appMaterialMoveSiteSave(command));

		assertEquals(0, records());
		assertEquals(10d, quantity());
	}
}

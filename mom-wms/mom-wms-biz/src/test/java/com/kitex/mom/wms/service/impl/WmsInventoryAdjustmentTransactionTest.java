	@Test
	void concurrentRetryStillBooksOnlyOnce() throws Exception {
		var executor = Executors.newFixedThreadPool(2);

		try {
			var one = executor.submit(() -> {
				scope();
				try {
					return service.adjust(command(7));
				} finally {
					clear();
				}
			});
			var two = executor.submit(() -> {
				scope();
				try {
					return service.adjust(command(7));
				} finally {
					clear();
				}
			});
			assertTrue(one.get(10, TimeUnit.SECONDS));
			assertTrue(two.get(10, TimeUnit.SECONDS));
			assertEquals(7d, db.queryForObject("SELECT quantity FROM stock", Double.class));
			assertEquals(1, db.queryForObject("SELECT COUNT(*) FROM bill", Integer.class));
		} finally {
			executor.shutdownNow();
		}
	}


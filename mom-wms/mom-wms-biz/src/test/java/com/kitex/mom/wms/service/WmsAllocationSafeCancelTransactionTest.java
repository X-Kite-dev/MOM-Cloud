	@Test
	void unexecutedRequestWithMissingOptionalExecutionFieldsCanStillBeSealed() {
		var original = command();
		original.setMatBatch(null);
		original.setSupplierCode(null);
		original.setMatUnit(null);
		var input = new Cancellation(original, "原提交字段不完整，取消后重新办理");
		try (var factory = jakarta.validation.Validation.buildDefaultValidatorFactory()) {
			assertTrue(factory.getValidator().validate(input).isEmpty(),
					"取消原请求不应套用实际调拨执行的批次和供应商必填约束");
		}
		assertEquals("CANCELLED", receipts.cancel(input).status());
		assertEquals(0, count("mom_wms.wms_allocation_bill"));
		assertEquals(0, count("flow"));
	}

	@Test
	void cancellationSealsAnUnexecutedOriginalWithoutCreatingABillOrMovingStock() {
		var first = receipts.cancel(new Cancellation(command(), "操作人撤销原请求"));
		assertEquals("CANCELLED", first.status());
		assertNull(first.billId());
		assertEquals(first, receipts.cancel(new Cancellation(command(), "后续重复说明")));
		assertEquals(first, receipts.lookup(command().getRequestId(), "W1"));
		assertThrows(CheckedException.class, () -> business.appSaveAllocationBill(command()));
		assertEquals(0, count("mom_wms.wms_allocation_bill"));
		assertEquals(1, count("mom_wms.wms_mobile_allocation_cancel_receipt"));
		assertEquals(10D, db.queryForObject("SELECT quantity FROM stock WHERE id=7", Double.class));
		assertEquals(0, count("flow"));
	}

	@Test
	void cancellationAfterCompletionReturnsOriginalWithoutUndoingTheTransfer() {
		assertTrue(business.appSaveAllocationBill(command()));
		var confirmed = receipts.lookup(command().getRequestId(), "W1");
		assertEquals(confirmed, receipts.cancel(new Cancellation(command(), "核对结果")));
		assertEquals("CONFIRMED", confirmed.status());
		assertEquals(1, count("mom_wms.wms_allocation_bill"));
		assertEquals(0, count("mom_wms.wms_mobile_allocation_cancel_receipt"));
		assertEquals(8D, db.queryForObject("SELECT quantity FROM stock WHERE id=7", Double.class));
		assertEquals(2, count("flow"));
	}

	@Test
	void changedPayloadActorOrFactoryCannotReuseACancelledOriginal() {
		receipts.cancel(new Cancellation(command(), "撤销"));
		var changed = command();
		changed.setOperateNum(3D);
		assertThrows(CheckedException.class, () -> receipts.cancel(new Cancellation(changed, "撤销")));
		identity("other", "F1", 1L);
		assertThrows(CheckedException.class, () -> receipts.lookup(command().getRequestId(), "W1"));
		identity("operator", "F2", 1L);
		assertThrows(CheckedException.class, () -> receipts.lookup(command().getRequestId(), "W1"));
	}

	@Test
	void failedCancellationInsertCreatesNoFalseTerminalAndOriginalCanStillExecute() {
		rejectCancellation = true;
		assertThrows(CheckedException.class, () -> receipts.cancel(new Cancellation(command(), "撤销")));
		assertEquals("NOT_CONFIRMED", receipts.lookup(command().getRequestId(), "W1").status());
		rejectCancellation = false;
		assertTrue(business.appSaveAllocationBill(command()));
	}

	@Test
	void failedMovementRollsBackBeforeTheOriginalIsSafelyCancelled() {
		failMove = true;
		assertThrows(CheckedException.class, () -> business.appSaveAllocationBill(command()));
		assertEquals("CANCELLED", receipts.cancel(new Cancellation(command(), "原执行失败后撤销")).status());
		assertEquals(0, count("mom_wms.wms_allocation_bill"));
		assertEquals(10D, db.queryForObject("SELECT quantity FROM stock WHERE id=7", Double.class));
	}

	@Test
	void executionAndCancellationCompetitionHaveOneCommittedOutcome() throws Exception {
		var pool = Executors.newFixedThreadPool(2);
		var start = new CountDownLatch(1);
		try {
			var execute = pool.submit(() -> {
				identity("operator", "F1", 1L);
				start.await();
				try {
					business.appSaveAllocationBill(command());
				} catch (CheckedException expected) {
					return "CANCELLED";
				}
				return "CONFIRMED";
			});
			var cancel = pool.submit(() -> {
				identity("operator", "F1", 1L);
				start.await();
				return receipts.cancel(new Cancellation(command(), "并发撤销")).status();
			});
			start.countDown();
			String result = execute.get(10, TimeUnit.SECONDS);
			assertEquals(result, cancel.get(10, TimeUnit.SECONDS));
			int executed = "CONFIRMED".equals(result) ? 1 : 0;
			assertEquals(executed, count("mom_wms.wms_allocation_bill"));
			assertEquals(1 - executed, count("mom_wms.wms_mobile_allocation_cancel_receipt"));
			assertEquals(10D - executed * 2D, db.queryForObject("SELECT quantity FROM stock WHERE id=7", Double.class));
			assertEquals(executed * 2, count("flow"));
		} finally {
			pool.shutdownNow();
		}
	}

	@SuppressWarnings("unchecked")
	private <T> T proxy(T target) {
		var factory = new ProxyFactory(target);
		factory.setProxyTargetClass(true);
		factory.addAdvice(new TransactionInterceptor(transactions, new AnnotationTransactionAttributeSource()));
		return (T) factory.getProxy();
	}

	private WmsAllocationBillEntity select(Wrapper<?> wrapper) {
		String sql = "SELECT payload FROM mom_wms.wms_allocation_bill " + wrapper.getCustomSqlSegment();
		var matcher = Pattern.compile("#\\{ew\\.paramNameValuePairs\\.(\\w+)(?:,[^}]*)?}").matcher(sql);
		var values = new ArrayList<Object>();
		var output = new StringBuilder();
		var params = ((AbstractWrapper<?, ?, ?>) wrapper).getParamNameValuePairs();
		while (matcher.find()) {
			values.add(params.get(matcher.group(1)));
			matcher.appendReplacement(output, "?");
		}
		matcher.appendTail(output);
		var rows = db.query(output.toString(),
				(r, n) -> JSONUtil.toBean(r.getString(1), WmsAllocationBillEntity.class), values.toArray());
		return rows.isEmpty() ? null : rows.get(0);
	}


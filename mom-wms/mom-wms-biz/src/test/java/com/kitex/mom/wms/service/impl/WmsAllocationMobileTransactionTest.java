class WmsAllocationMobileTransactionTest {

    @AfterEach
    void clearContext() {
        TenantContextHolder.clear();
        FactoryContextHolder.clear();
        SecurityContextHolder.clearContext();
    }

    @ParameterizedTest
    @ValueSource(booleans = {false, true})
    void failedCompletionProofRollsBackMobileBillAndStockMove(boolean unitMismatch) {
        var dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:mobile-allocation-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", "");
        dataSource.setDriverClassName("org.h2.Driver");
        var db = new JdbcTemplate(dataSource);
        db.execute("create table allocation_bill (id bigint primary key, bill_no varchar(80))");
        db.execute("create table stock (id bigint primary key, quantity double precision)");
        db.execute("create table flow (id bigint generated by default as identity primary key, "
                + "source_stock_id bigint, barcode varchar(80))");
        db.update("insert into stock values (7, 1)");

        TenantContextHolder.setTenantId(1L);
        FactoryContextHolder.setFactoryCode("F1");
        var actor = mock(MomUser.class);
        when(actor.getUsername()).thenReturn("warehouse-operator");
        when(actor.getName()).thenReturn("Warehouse operator");
        SecurityContextHolder.getContext().setAuthentication(
                new UsernamePasswordAuthenticationToken(actor, null, List.of()));

        var target = mock(WmsAllocationBillServiceImpl.class, CALLS_REAL_METHODS);
        var warehouses = mock(RemoteWarehouseService.class);
        var locations = mock(RemoteWarehouseLocationService.class);
        var permissions = mock(PermissionService.class);
        var guard = mock(WmsWarehouseBusinessGuard.class);
        var stocks = mock(WmsLiveStockService.class);
        var flows = mock(WmsInoutFlowMapper.class);
        var bills = mock(WmsAllocationBillMapper.class);
        ReflectionTestUtils.setField(target, "remoteWarehouseService", warehouses);
        ReflectionTestUtils.setField(target, "remoteWarehouseLocationService", locations);
        ReflectionTestUtils.setField(target, "permissionService", permissions);
        ReflectionTestUtils.setField(target, "warehouseBusinessGuard", guard);
        ReflectionTestUtils.setField(target, "wmsLiveStockService", stocks);
        ReflectionTestUtils.setField(target, "wmsInoutFlowMapper", flows);
        ReflectionTestUtils.setField(target, "baseMapper", bills);
        ReflectionTestUtils.setField(target, "mobileCancelReceipts", mock(WmsAllocationMobileCancelReceiptMapper.class));
        when(warehouses.getByCode("W1")).thenReturn(R.ok(warehouse("W1")));
        when(warehouses.getByCode("W2")).thenReturn(R.ok(warehouse("W2")));
        when(locations.getByCode("S1")).thenReturn(R.ok(location("S1", "W1")));
        when(locations.getByCode("T1")).thenReturn(R.ok(location("T1", "W2")));
        when(permissions.hasPermission(anyString(), anyString())).thenReturn(true);
        when(guard.check(anyString(), eq("allocation"), anyBoolean())).thenReturn(true);
        when(bills.lockAgentTransfer("MOBILE_REQUEST:1:request-7")).thenReturn(1);
        doReturn(null).when(target).getOne(any(Wrapper.class), eq(false));
        doReturn(0L).when(target).count(any(Wrapper.class));
        doAnswer(call -> {
            assertTrue(TransactionSynchronizationManager.isActualTransactionActive());
            WmsAllocationBillEntity bill = call.getArgument(0);
            bill.setId(50L);
            return db.update("insert into allocation_bill values (?, ?)", bill.getId(), bill.getBillNo()) == 1;
        }).when(target).save(any(WmsAllocationBillEntity.class));
        when(stocks.billStockMoveWithEvidence(any())).thenAnswer(call -> {
            assertTrue(TransactionSynchronizationManager.isActualTransactionActive());
            db.update("update stock set quantity = 0 where id = 7");
            var source = new WmsLiveStockEntity().setFactoryCode("F1")
                    .setWarehouseCode("W1").setSiteCode("S1")
                    .setMatCode("M1").setMatUnit(unitMismatch ? "KG" : "EA").setMatNum(1d)
                    .setMatBarcode("SERIAL-7").setSerialManaged(true);
            source.setId(7L);
            return List.of(new WmsStockMoveSlice(source, 70L, 1d));
        });
        when(flows.insert(any(WmsInoutFlowEntity.class))).thenAnswer(call -> {
            WmsInoutFlowEntity flow = call.getArgument(0);
            if (flow.getSourceFlowId() != null) {
                return 0;
            }
            db.update("insert into flow (source_stock_id, barcode) values (?, ?)",
                    flow.getSourceStockId(), flow.getMatBarcode());
            flow.setId(db.queryForObject("select max(id) from flow", Long.class));
            return 1;
        });

        var proxy = new ProxyFactory(target);
        proxy.setProxyTargetClass(true);
        proxy.addAdvice(new TransactionInterceptor(new DataSourceTransactionManager(dataSource),
                new AnnotationTransactionAttributeSource()));
        var service = (WmsAllocationBillServiceImpl) proxy.getProxy();

        assertThrows(CheckedException.class, () -> service.appSaveAllocationBill(command()));
        verify(stocks).billStockMoveWithEvidence(any());
        verify(flows, times(unitMismatch ? 0 : 2)).insert(any(WmsInoutFlowEntity.class));
        var lockBeforeReceipt = inOrder(bills, target);
        lockBeforeReceipt.verify(bills).lockAgentTransfer("MOBILE_REQUEST:1:request-7");
        lockBeforeReceipt.verify(target).getOne(any(Wrapper.class), eq(false));
        assertEquals(0, db.queryForObject("select count(*) from allocation_bill", Integer.class));
        assertEquals(1d, db.queryForObject("select quantity from stock where id = 7", Double.class));
        assertEquals(0, db.queryForObject("select count(*) from flow", Integer.class));
    }

    private WmsAllocationBillAppDTO command() {
        var command = new WmsAllocationBillAppDTO();
        command.setRequestId("request-7");
        command.setBillNo("TR-7");
        command.setOldWarehouseCode("W1");
        command.setOldSiteCode("S1");
        command.setNewWarehouseCode("W2");
        command.setNewSiteCode("T1");
        command.setMatCode("M1");
        command.setMatUnit("EA");
        command.setOperateNum(1d);
        command.setSourceStockId(7L);
        command.setMatBarcode("SERIAL-7");
        return command;
    }

    private MdmWarehouseEntity warehouse(String code) {
        var warehouse = new MdmWarehouseEntity();
        warehouse.setWarehouseCode(code);
        warehouse.setWarehouseName(code);
        warehouse.setFactoryCode("F1");
        warehouse.setTenantId(1L);
        warehouse.setStatus(true);
        return warehouse;
    }

    private MdmWarehouseLocationEntity location(String code, String warehouse) {
        var location = new MdmWarehouseLocationEntity();
        location.setLocationCode(code);
        location.setLocationName(code);
        location.setWarehouseCode(warehouse);
        location.setFactoryCode("F1");
        location.setTenantId(1L);
        location.setStatus(true);
        return location;
    }
}

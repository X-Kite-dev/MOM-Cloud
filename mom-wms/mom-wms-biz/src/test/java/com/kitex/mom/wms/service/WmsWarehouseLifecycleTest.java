	@Test
	void permanentCleanupDeletesOnlyExactConfigurationAndWholePreviewSubtreeAndIsRetryable() {
		cleanupFixture();
		db.update("insert into wms_warehouse_dashboard_policy values"
				+ "(1,'F1','W1'),(1,'F1','W10'),(2,'F1','W1'),(1,'F2','W1')");
		db.update("insert into wms_warehouse_location_map values"
				+ "(1,'F1','W1'),(1,'F1','W10'),(2,'F1','W1'),(1,'F2','W1')");
		db.update("insert into wms_inventory_scope_policy values"
				+ "(1,'F1','W1'),(1,'F1','W10'),(2,'F1','W1'),(1,'F2','W1')");
		db.update("insert into wms_inventory_count_template values"
				+ "(1,'F1','W1','CYCLE_A'),(1,'F1','W10','CYCLE_B'),"
				+ "(2,'F1','W1','CYCLE_C'),(1,'F2','W1','CYCLE_D')");

		assertTrue(service.cleanup("W1"));
		assertTrue(service.cleanup("W1"));

		assertEquals(List.of("other", "foreign", "factory"), db.queryForList(
				"select biz_type from wms_warehouse_biz order by biz_type desc", String.class));
		assertEquals(List.of(13L, 14L, 15L),
				db.queryForList("select id from wms_warehouse_menu order by id", Long.class));
		assertEquals(3, db.queryForObject("select count(*) from wms_warehouse_dashboard_policy", Integer.class));
		assertEquals(3, db.queryForObject("select count(*) from wms_warehouse_location_map", Integer.class));
		assertEquals(3, db.queryForObject("select count(*) from wms_inventory_scope_policy", Integer.class));
		assertEquals(3, db.queryForObject("select count(*) from wms_inventory_count_template", Integer.class));

		verify(menus, times(2)).removeWarehouseMenus("W1");
	}

	@Test
	void unknownFalseFailedOrThrowingSystemCleanupRollsBackLocalConfiguration() {
		cleanupFixture();
		db.update("insert into wms_warehouse_dashboard_policy values(1,'F1','W1')");

		for (R<Boolean> response : List.of(R.<Boolean>ok(), R.ok(false), R.<Boolean>failed("offline"))) {
			when(menus.removeWarehouseMenus("W1")).thenReturn(response);

			assertThrows(CheckedException.class, () -> service.cleanup("W1"));

			assertEquals(5, db.queryForObject("select count(*) from wms_warehouse_biz", Integer.class));
			assertEquals(6, db.queryForObject("select count(*) from wms_warehouse_menu", Integer.class));
			assertEquals(1, db.queryForObject("select count(*) from wms_warehouse_dashboard_policy", Integer.class));
		}

		when(menus.removeWarehouseMenus("W1")).thenReturn(null);

		assertThrows(CheckedException.class, () -> service.cleanup("W1"));

		when(menus.removeWarehouseMenus("W1")).thenThrow(new IllegalStateException("timeout"));

		assertThrows(CheckedException.class, () -> service.cleanup("W1"));

		assertEquals(5, db.queryForObject("select count(*) from wms_warehouse_biz", Integer.class));
		assertEquals(6, db.queryForObject("select count(*) from wms_warehouse_menu", Integer.class));
		assertEquals(1, db.queryForObject("select count(*) from wms_warehouse_dashboard_policy", Integer.class));
	}


	@Test
	void cleanupRejectsActiveMissingForeignDuplicateAndUnknownWarehouseStates() {
		cleanupFixture();
		warehouse.setStatus(true);

		assertThrows(CheckedException.class, () -> service.cleanup("W1"));

		warehouse.setStatus(false);
		warehouse.setTenantId(2L);

		assertThrows(CheckedException.class, () -> service.cleanup("W1"));

		warehouse.setTenantId(1L);
		when(warehouses.getMenuConfigurationWarehouses()).thenReturn(R.ok(List.of(warehouse, warehouse)));

		assertThrows(CheckedException.class, () -> service.cleanup("W1"));

		when(warehouses.getMenuConfigurationWarehouses()).thenReturn(R.ok(List.of()));

		assertThrows(CheckedException.class, () -> service.cleanup("W1"));

		when(warehouses.getMenuConfigurationWarehouses()).thenReturn(R.ok());

		assertThrows(CheckedException.class, () -> service.cleanup("W1"));

		when(warehouses.getMenuConfigurationWarehouses()).thenReturn(null);

		assertThrows(CheckedException.class, () -> service.cleanup("W1"));

		assertEquals(5, db.queryForObject("select count(*) from wms_warehouse_biz", Integer.class));

		verify(menus, never()).removeWarehouseMenus(anyString());
	}


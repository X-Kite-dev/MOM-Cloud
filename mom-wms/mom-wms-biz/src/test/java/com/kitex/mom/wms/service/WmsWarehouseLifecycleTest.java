	@BeforeEach
	void setup() throws Exception {
		FactoryContextHolder.setFactoryCode("F1");
		TenantContextHolder.setTenantId(1L);
		var source = new DriverManagerDataSource("jdbc:h2:mem:wms-warehouse-references-" + UUID.randomUUID()
				+ ";DB_CLOSE_DELAY=-1", "sa", "");
		source.setDriverClassName("org.h2.Driver");
		db = new JdbcTemplate(source);
		Map<String, Set<String>> columns = new LinkedHashMap<>();
		for (String fixture : REFERENCES) {
			String[] fields = fixture.split(",");
			columns.computeIfAbsent(fields[0], ignored -> new LinkedHashSet<>()).add(fields[1]);
		}
		for (var entry : columns.entrySet()) {
			String sql = "create table " + entry.getKey()
					+ "(tenant_id bigint,factory_code varchar,del_flag varchar";
			for (String column : entry.getValue()) {
				sql += "," + column + " varchar";
			}
			db.execute(sql + ")");
		}

		db.execute("create table wms_warehouse_menu(id bigint generated by default as identity primary key,"
				+ "parent_id bigint,tenant_id bigint,factory_code "
				+ "varchar,path varchar,del_flag varchar)");
		db.execute("create table wms_warehouse_biz(tenant_id bigint,factory_code varchar,"
				+ "warehouse_code varchar,biz_type varchar,del_flag varchar)");
		db.execute("create table wms_warehouse_dashboard_policy(tenant_id bigint,factory_code varchar,"
				+ "warehouse_code varchar)");
		db.execute("create table wms_warehouse_location_map(tenant_id bigint,factory_code varchar,"
				+ "warehouse_code varchar)");
		db.execute("create table wms_inventory_scope_policy(tenant_id bigint,factory_code varchar,"
				+ "warehouse_code varchar)");
		db.execute("create table wms_inventory_count_template(tenant_id bigint,factory_code varchar,"
				+ "warehouse_code varchar,template_code varchar)");
		db.execute("create table wms_inventory_count_template_run(tenant_id bigint,factory_code varchar,"
				+ "template_code varchar,request_id varchar)");
		var configuration = new MybatisConfiguration();
		configuration.addMapper(WmsWarehouseLifecycleMapper.class);
		var factory = new MybatisSqlSessionFactoryBean();
		factory.setDataSource(source);
		factory.setConfiguration(configuration);
		var sessions = new SqlSessionTemplate(factory.getObject());
		warehouses = mock(RemoteWarehouseService.class);
		menus = mock(RemoteMenuService.class);
		warehouse = new MdmWarehouseEntity().setWarehouseCode("W1").setFactoryCode("F1").setStatus(false);
		warehouse.setTenantId(1L);
		when(warehouses.getMenuConfigurationWarehouses()).thenReturn(R.ok(List.of(warehouse)));
		when(menus.removeWarehouseMenus("W1")).thenReturn(R.ok(true));
		lifecycle = mock(WmsWarehouseLifecycleMapper.class,
				delegatesTo(sessions.getMapper(WmsWarehouseLifecycleMapper.class)));
		var target = new WmsWarehouseLifecycleService(lifecycle,
				mock(WmsWarehouseMenuMapper.class), warehouses, menus);
		var proxy = new ProxyFactory(target);
		proxy.setProxyTargetClass(true);
		proxy.addAdvice(new TransactionInterceptor(new DataSourceTransactionManager(source),
				new AnnotationTransactionAttributeSource()));
		service = (WmsWarehouseLifecycleService) proxy.getProxy();
	}

